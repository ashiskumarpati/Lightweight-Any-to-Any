def wiki_search(query, sentences=2):

    try:
        results = wikipedia.search(query)

        if not results:
            return None

        page = wikipedia.page(results[0])

        summary = wikipedia.summary(
            page.title,
            sentences=sentences
        )

        return summary

    except Exception:
        return None


def should_use_wiki(query):

    q = query.lower()

    keywords = [
        "who",
        "when",
        "where",
        "history",
        "capital",
        "president",
        "world cup"
    ]

    return any(k in q for k in keywords)


