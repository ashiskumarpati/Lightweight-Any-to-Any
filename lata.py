def train_step(batch):

    optimizer.zero_grad()

    images = batch["images"]

    captions = batch["captions"]

    image_embeddings = []

    text_embeddings = []

    # --------------------------------------------------------
    # ENCODE WHOLE BATCH
    # --------------------------------------------------------

    for img, text in zip(images, captions):

        # ----------------------------------------------------
        # IMAGE EMBEDDING
        # ----------------------------------------------------

        z_img = image_proj(
            encode_image(img)
        )

        # ----------------------------------------------------
        # TEXT EMBEDDING
        # ----------------------------------------------------

        z_txt = text_proj(
            encode_text(text)
        )

        image_embeddings.append(z_img)

        text_embeddings.append(z_txt)

    # --------------------------------------------------------
    # STACK BATCH
    # --------------------------------------------------------

    z_img = torch.cat(
        image_embeddings,
        dim=0
    )

    z_txt = torch.cat(
        text_embeddings,
        dim=0
    )

    # --------------------------------------------------------
    # NORMALIZATION
    # --------------------------------------------------------

    z_img = F.normalize(
        z_img,
        dim=-1
    )

    z_txt = F.normalize(
        z_txt,
        dim=-1
    )

    # --------------------------------------------------------
    # CONTRASTIVE LOSS
    # --------------------------------------------------------

    loss = contrastive_loss(
        z_img,
        z_txt
    )

    # --------------------------------------------------------
    # BACKPROPAGATION
    # --------------------------------------------------------

    loss.backward()

    optimizer.step()

    return loss.item()


