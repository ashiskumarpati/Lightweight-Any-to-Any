# ------------------------------------------------------------
# CONTRASTIVE LOSS
# ------------------------------------------------------------

def contrastive_loss(
    z1,
    z2,
    temperature=0.07
):

    z1 = F.normalize(z1, dim=-1)

    z2 = F.normalize(z2, dim=-1)

    logits = z1 @ z2.T / temperature

    labels = torch.arange(
        z1.size(0)
    ).to(z1.device)

    loss_i = F.cross_entropy(
        logits,
        labels
    )

    loss_t = F.cross_entropy(
        logits.T,
        labels
    )

    return (loss_i + loss_t) / 2


