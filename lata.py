# 21. COMPUTATIONAL EFFICIENCY
# ============================================================

def computational_efficiency_report(
    sample_img,
    sample_text="Explain AI",
    sample_audio_path=None,
    runs=3
):

    def measure(fn, *args, **kwargs):

        times = []

        for _ in range(runs):

            start = time.perf_counter()

            fn(*args, **kwargs)

            end = time.perf_counter()

            times.append(end - start)

        return (
            float(np.mean(times)),
            float(np.std(times))
        )

    # --------------------------------------------------------
    # TEXT GENERATION
    # --------------------------------------------------------

    text_time, text_std = measure(

        qwen_reason,

        sample_text,

        max_new_tokens=80
    )

    # --------------------------------------------------------
    # TEXT → IMAGE
    # --------------------------------------------------------

    img_time, img_std = measure(

        pipe,

        sample_text,

        num_inference_steps=30,

        guidance_scale=7.5
    )

    # --------------------------------------------------------
    # IMAGE → IMAGE
    # --------------------------------------------------------

    sample_img = (
        sample_img.convert("RGB")
        .resize((512, 512))
    )

    img2img_time, img2img_std = measure(

        img2img_pipe,

        "A cinematic version of the image",

        image=sample_img,

        strength=0.5,

        guidance_scale=7.5,

        num_inference_steps=30
    )

    # --------------------------------------------------------
    # CLIP ENCODING
    # --------------------------------------------------------

    clip_time, clip_std = measure(
        encode_image,
        sample_img
    )

    # --------------------------------------------------------
    # WHISPER
    # --------------------------------------------------------

    if sample_audio_path is not None:

        def whisper_run():

            return whisper_model.transcribe(
                sample_audio_path
            )

        audio_time, audio_std = measure(
            whisper_run
        )

    else:

        audio_time, audio_std = None, None

    # --------------------------------------------------------
    # BUILD TABLE
    # --------------------------------------------------------

    data = [

        [
            "Text Generation (Qwen)",
            text_time,
            text_std
        ],

        [
            "Text → Image (Stable Diffusion)",
            img_time,
            img_std
        ],

        [
            "Image → Image (Img2Img)",
            img2img_time,
            img2img_std
        ],

        [
            "Image Encoding (CLIP)",
            clip_time,
            clip_std
        ]

    ]

    if audio_time is not None:

        data.append([

            "Audio Transcription (Whisper)",

            audio_time,

            audio_std

        ])

    df = pd.DataFrame(

        data,

        columns=[
            "Component",
            "Avg Latency (s)",
            "Std Dev"
        ]
    )

    print("\n==============================")
    print("COMPUTATIONAL EFFICIENCY")
    print("==============================\n")

    print(df)

    return df

