chat_history = []

def qwen_reason(
    prompt,
    max_new_tokens=150
):

    global chat_history

    messages = [

        {
            "role": "system",
            "content":
            "You are a precise and factual multimodal AI assistant."
        }

    ] + chat_history + [

        {
            "role": "user",
            "content": prompt
        }

    ]

    text = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True
    )

    inputs = tokenizer(
        text,
        return_tensors="pt"
    ).to(DEVICE)

    with torch.no_grad():

        outputs = qwen.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            temperature=0.5,
            top_p=0.9
        )

    response = tokenizer.decode(
        outputs[0][inputs.input_ids.shape[-1]:],
        skip_special_tokens=True
    ).strip()

    # --------------------------------------------------------
    # STORE CHAT HISTORY
    # --------------------------------------------------------

    chat_history.append({
        "role": "user",
        "content": prompt
    })

    chat_history.append({
        "role": "assistant",
        "content": response
    })

    # --------------------------------------------------------
    # KEEP RECENT HISTORY
    # --------------------------------------------------------

    if len(chat_history) > 6:
        chat_history = chat_history[-6:]

    return response.split("Note:")[0].strip()

