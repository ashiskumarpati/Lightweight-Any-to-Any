def any_to_any(
    inputs,
    instruction="",
    output_modality="text"
):

    # --------------------------------------------------------
    # HANDLE SINGLE INPUT
    # --------------------------------------------------------

    if not isinstance(inputs, list):
        inputs = [inputs]

    context_texts = []

    embeddings = []

    # ========================================================
    # PROCESS INPUTS
    # ========================================================

    for inp in inputs:

        # ----------------------------------------------------
        # IMAGE INPUT
        # ----------------------------------------------------

        if isinstance(inp, Image.Image):

            caption = caption_image(inp)

            context_texts.append(
                f"[Image]: {caption}"
            )

            emb = text_proj(
                encode_text(caption)
            )

            embeddings.append(emb)

        # ----------------------------------------------------
        # AUDIO INPUT
        # ----------------------------------------------------

        elif isinstance(inp, str) and inp.endswith(
            (".wav", ".mp3", ".webm")
        ):

            # ------------------------------------------------
            # SPEECH TO TEXT
            # ------------------------------------------------

            try:

                result = whisper_model.transcribe(inp)

                audio_text = result["text"]

            except:

                audio_text = "Audio input"

            context_texts.append(
                f"[Audio]: {audio_text}"
            )

            # ------------------------------------------------
            # SEMANTIC EMBEDDING
            # ------------------------------------------------

            text_embedding = encode_text(
                audio_text
            )

            # ------------------------------------------------
            # ACOUSTIC EMBEDDING
            # ------------------------------------------------

            acoustic_embedding = encode_audio(inp)

            # ------------------------------------------------
            # CONCATENATE
            # ------------------------------------------------

            combined_embedding = torch.cat(

                [
                    text_embedding,
                    acoustic_embedding
                ],

                dim=-1

            )

            # ------------------------------------------------
            # PROJECT TO LATENT SPACE
            # ------------------------------------------------

            emb = audio_proj(
                combined_embedding
            )

            embeddings.append(emb)

        # ----------------------------------------------------
        # TEXT INPUT
        # ----------------------------------------------------

        else:

            text = str(inp)

            context_texts.append(
                f"[Text]: {text}"
            )

            emb = text_proj(
                encode_text(text)
            )

            embeddings.append(emb)

    # ========================================================
    # MULTIMODAL FUSION
    # ========================================================

    x = torch.stack(
        embeddings,
        dim=1
    )

    fused = fusion_pool(
        fusion(x)
    )

    fused_context = "\n".join(
        context_texts
    )

    # ========================================================
    # TEXT OUTPUT
    # ========================================================

    if output_modality == "text":

        query = (
            instruction
            if instruction
            else fused_context
        )

        query = query[:100]

        wiki_context = None

        if should_use_wiki(query):

            wiki_context = wiki_search(query)

            if wiki_context:

                fused_context += (
                    f"\n[Wikipedia]: "
                    f"{wiki_context}\n"
                )

        prompt = f"""
        You are a factual AI assistant.

        Use Wikipedia information if available.
        Do NOT hallucinate.

        Context:
        {fused_context}

        Instruction:
        {instruction}

        Answer correctly and concisely:
        """

        return qwen_reason(prompt)

    # ========================================================
    # IMAGE OUTPUT
    # ========================================================

    elif output_modality == "image":

        # ----------------------------------------------------
        # CHECK FOR INPUT IMAGE
        # ----------------------------------------------------

        original_image = None

        for inp in inputs:

            if isinstance(inp, Image.Image):

                original_image = (
                    inp.convert("RGB")
                    .resize((512, 512))
                )

                break

        # ----------------------------------------------------
        # GENERATE IMAGE PROMPT
        # ----------------------------------------------------

        image_prompt = qwen_reason(
            f"""
            Create a Stable Diffusion prompt
            under 50 words.

            Context:
            {fused_context}

            Instruction:
            {instruction}

            Include:
            subject,
            environment,
            lighting,
            artistic style,
            highly detailed,
            cinematic.
            """,
            max_new_tokens=80
        )

        print("FINAL PROMPT:", image_prompt)

        # ----------------------------------------------------
        # IMAGE-TO-IMAGE
        # ----------------------------------------------------

        if original_image is not None:

            return img2img_pipe(

                prompt=image_prompt[:200],

                image=original_image,

                strength=0.5,

                guidance_scale=7.5,

                num_inference_steps=40

            ).images[0]

        # ----------------------------------------------------
        # TEXT-TO-IMAGE
        # ----------------------------------------------------

        else:

            return pipe(

                image_prompt[:200],

                num_inference_steps=30,

                guidance_scale=7.5

            ).images[0]

    # ========================================================
    # AUDIO OUTPUT
    # ========================================================

    elif output_modality == "audio":

        prompt = f"""
        Context:
        {fused_context}

        Instruction:
        {instruction}

        Explain naturally for speech:
        """

        text_output = qwen_reason(prompt)

        return decode_audio(text_output)

