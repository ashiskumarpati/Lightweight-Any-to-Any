# COSINE SIMILARITY
# ------------------------------------------------------------

def compute_cosine_similarity(
    vec1,
    vec2
):

    if vec1.dim() == 1:
        vec1 = vec1.unsqueeze(0)

    if vec2.dim() == 1:
        vec2 = vec2.unsqueeze(0)

    vec1 = F.normalize(
        vec1.float(),
        dim=-1
    )

    vec2 = F.normalize(
        vec2.float(),
        dim=-1
    )

    similarity = (
        vec1 * vec2
    ).sum(dim=-1)

    return similarity.mean().item()

