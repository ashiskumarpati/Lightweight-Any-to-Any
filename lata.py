# WORD ERROR RATE
# ------------------------------------------------------------

def compute_wer(
    audio_path,
    reference_text
):

    result = whisper_model.transcribe(
        audio_path
    )

    hypothesis = result["text"].strip()

    ref_norm = normalize_text(
        reference_text
    )

    hyp_norm = normalize_text(
        hypothesis
    )

    try:

        wer_score = wer(
            ref_norm,
            hyp_norm
        )

    except:

        wer_score = None

    P, R, F1 = bertscore_score(

        [hypothesis],
        [reference_text],

        lang="en",

        verbose=False
    )

    bert_f1 = F1.mean().item()

    return {

        "WER": wer_score,

        "Audio_BERTScore_F1": bert_f1,

        "Transcription": hypothesis

    }


