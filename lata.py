def encode_text(text):

    tokens = tokenizer(
        text,
        return_tensors="pt",
        truncation=True
    )

    input_ids = tokens.input_ids.to(DEVICE)

    with torch.no_grad():

        hidden = qwen.get_input_embeddings()(input_ids)

    hidden = hidden.mean(dim=1)

    return hidden


