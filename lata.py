    sns.scatterplot(
        x=reduced[:, 0],
        y=reduced[:, 1],
        hue=labels
    )

    plt.title("t-SNE Latent Space")

    plt.savefig(
        "results/tsne_latent_space.png",
        dpi=300,
        bbox_inches="tight"
    )

    plt.show()


