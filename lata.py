def visualize_attention(inputs):

    embeddings = []

    labels = []

    for inp in inputs:

        if isinstance(inp, Image.Image):

            caption = caption_image(inp)

            emb = text_proj(
                encode_text(caption)
            )

            labels.append("Image")

        elif isinstance(inp, str) and inp.endswith(
            (".wav", ".mp3", ".webm")
        ):

            result = whisper_model.transcribe(inp)

            text = result["text"]

            emb = audio_proj(
                torch.cat(
                    [
                        encode_text(text),
                        encode_audio(inp)
                    ],
                    dim=-1
                )
            )

            labels.append("Audio")

        else:

            emb = text_proj(
                encode_text(str(inp))
            )

            labels.append("Text")

        embeddings.append(emb)

    x = torch.stack(
        embeddings,
        dim=1
    )

    _, weights = fusion_pool(
        fusion(x),
        return_weights=True
    )

    weights = weights.squeeze(-1).detach().cpu().numpy()

    plt.figure(figsize=(6, 4))

    sns.heatmap(
        weights,
        annot=True,
        xticklabels=labels,
        yticklabels=["Attention"]
    )

    plt.title("Attention Heatmap")

    plt.savefig(
        "results/attention_heatmap.png",
        dpi=300,
        bbox_inches="tight"
    )

    plt.show()

