def compute_clipscore(
    image,
    prompt
):

    image_tensor = clip_preprocess(
        image
    ).unsqueeze(0).to(DEVICE).float()

    text_tokens = clip_tokenizer(
        [prompt]
    ).to(DEVICE)

    with torch.no_grad():

        image_features = clip_model.encode_image(
            image_tensor
        )

        text_features = clip_model.encode_text(
            text_tokens
        )

        image_features = F.normalize(
            image_features.float(),
            dim=-1
        )

        text_features = F.normalize(
            text_features.float(),
            dim=-1
        )

        score = (
            image_features * text_features
        ).sum(dim=-1)

    return score.item()


