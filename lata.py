    if (
        generated_image is not None
        and image_prompt is not None
    ):

        results["CLIPScore"] = compute_clipscore(
            generated_image,
            image_prompt
        )

    # ========================================================
    # AUDIO EVALUATION
    # ========================================================

    if (
        generated_audio is not None
        and reference_audio_text is not None
    ):

        results["WER"] = compute_wer(
            generated_audio,
            reference_audio_text
        )

    # ========================================================
    # LATENT EVALUATION
    # ========================================================

    if (
        latent1 is not None
        and latent2 is not None
    ):

        results["Cosine_Similarity"] = compute_cosine_similarity(
            latent1,
            latent2
        )

    return results

